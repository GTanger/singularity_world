    function bindWorldMapEvents() {
        var overlay = document.getElementById('sw-world-map-overlay');
        var closeBtn = document.getElementById('btn-wm-close');
        var centerBtn = document.getElementById('btn-wm-center');
        var zoomBtn = document.getElementById('btn-wm-zoom');
        var viewportEl = document.getElementById('sw-world-map-viewport');

        if (overlay && !overlay._bound) {
            overlay._bound = true;
            overlay.addEventListener('click', function (e) {
                var legendPopup = document.getElementById('sw-map-legend-popup');
                var legendBtn = document.getElementById('btn-map-legend');
                if (legendPopup && !legendPopup.hasAttribute('hidden')) {
                    if (!legendPopup.contains(e.target) && !(legendBtn && legendBtn.contains(e.target))) {
                        legendPopup.setAttribute('hidden', '');
                        if (legendBtn) legendBtn.setAttribute('aria-expanded', 'false');
                    }
                }
                if (e.target === overlay) {
                    closeWorldMapModal();
                }
            });
        }
        if (closeBtn && !closeBtn._bound) {
            closeBtn._bound = true;
            closeBtn.addEventListener('click', closeWorldMapModal);
        }
        if (centerBtn && !centerBtn._bound) {
            centerBtn._bound = true;
            centerBtn.addEventListener('click', centerWorldMapOnPlayer);
        }
        if (zoomBtn && !zoomBtn._bound) {
            zoomBtn._bound = true;
            zoomBtn.addEventListener('click', function () {
                _isCompactZoom = !_isCompactZoom;
                zoomBtn.textContent = _isCompactZoom ? '標準微地名' : '緊湊全覽';
                renderWorldMapContent();
                setTimeout(centerWorldMapOnPlayer, 20);
            });
        }

        if (viewportEl && !viewportEl._dragBound) {
            viewportEl._dragBound = true;
            var isDragging = false;
            var startX = 0, startY = 0;
            var initScrollLeft = 0, initScrollTop = 0;

            viewportEl.addEventListener('pointerdown', function (e) {
                if (e.target && e.target.tagName === 'BUTTON') return;
                isDragging = true;
                _didDragWorldMap = false;
                startX = e.clientX;
                startY = e.clientY;
                initScrollLeft = viewportEl.scrollLeft;
                initScrollTop = viewportEl.scrollTop;
                try { viewportEl.setPointerCapture(e.pointerId); } catch (_) {}
            });

            viewportEl.addEventListener('pointermove', function (e) {
                if (!isDragging) return;
                var dx = e.clientX - startX;
                var dy = e.clientY - startY;
                if (Math.hypot(dx, dy) > 5) {
                    _didDragWorldMap = true;
                }
                viewportEl.scrollLeft = initScrollLeft - dx;
                viewportEl.scrollTop = initScrollTop - dy;
            });

            var stopDrag = function (e) {
                if (isDragging) {
                    isDragging = false;
                    try { viewportEl.releasePointerCapture(e.pointerId); } catch (_) {}
                    setTimeout(function () {
                        _didDragWorldMap = false;
                    }, 60);
                }
            };
            viewportEl.addEventListener('pointerup', stopDrag);
            viewportEl.addEventListener('pointercancel', stopDrag);
        }

        if (!window._swWmKeyBound) {
            window.addEventListener('keydown', function (e) {
                if (e.key === 'Escape') {
                    var legendPopup = document.getElementById('sw-map-legend-popup');
                    var legendBtn = document.getElementById('btn-map-legend');
                    if (legendPopup && !legendPopup.hasAttribute('hidden')) {
                        legendPopup.setAttribute('hidden', '');
                        if (legendBtn) legendBtn.setAttribute('aria-expanded', 'false');
                        return;
                    }
                    var ov = document.getElementById('sw-world-map-overlay');
                    if (ov && !ov.hasAttribute('hidden')) {
                        closeWorldMapModal();
                    }
                    return;
                }
                // WASD and Arrow key cardinal movement when not typing in an input
                var targetTag = e.target && e.target.tagName;
                if (targetTag === 'INPUT' || targetTag === 'TEXTAREA' || (e.target && e.target.isContentEditable)) {
                    return;
                }
                var key = e.key;
                var dirMap = {
                    'ArrowUp': '北', 'KeyW': '北', 'w': '北', 'W': '北',
                    'ArrowDown': '南', 'KeyS': '南', 's': '南', 'S': '南',
                    'ArrowLeft': '西', 'KeyA': '西', 'a': '西', 'A': '西',
                    'ArrowRight': '東', 'KeyD': '東', 'd': '東', 'D': '東'
                };
                var targetDir = dirMap[key];
                if (targetDir && _lastCardinalByDir && _lastCardinalByDir[targetDir]) {
                    var item = _lastCardinalByDir[targetDir];
                    if (item && item.walkable) {
                        e.preventDefault();
                        executeCardinalStep(item, targetDir, lastPlayerX, lastPlayerY);
                    }
                }
            });
        }
    }

