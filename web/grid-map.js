    function shortPlaceLabel(rawName, fallbackDir) {
        var rawTrimmed = String(rawName || '').trim();
        if (EXACT_SHORT_LABELS[rawTrimmed]) {
            return EXACT_SHORT_LABELS[rawTrimmed];
        }

        var s = rawTrimmed;
        if (s.indexOf('・') !== -1 || s.indexOf('·') !== -1) {
            var parts = s.split(/[・·]/);
            var joined = parts.map(function (p) { return p.trim(); }).join('');
            if (EXACT_SHORT_LABELS[joined]) {
                return EXACT_SHORT_LABELS[joined];
            }
            if (parts.length === 2) {
                var p0 = parts[0].trim();
                var p1 = parts[1].trim();
                // 一般荒野地形與道路（如「長風草甸・草原」、「長風草甸・道路」、「赤石坡・礦坡」）優先顯示前段區名
                var genericTerrainSuffixes = /^(草原|草甸|草場|密林|山脊|幽沼|泥澤|深水|海灣|冰峰|雪巔|雪林|山隘|礦道|礦坡|礦谷|沙礫|海岬|巨岩|楓林|清流|古徑|山徑|岩岸|淺灣|礫灣|溪谷|雲杉|林道|泥口|深潭|峭壁|道路|幹道|山道|棧道|木橋)$/;
                if (genericTerrainSuffixes.test(p1) && p0) {
                    s = p0;
                } else {
                    s = p1;
                }
            } else {
                s = parts[parts.length - 1].trim();
            }
            if (EXACT_SHORT_LABELS[s]) {
                return EXACT_SHORT_LABELS[s];
            }
        }
        if (!s && fallbackDir) {
            s = String(fallbackDir).trim();
        }
        if (EXACT_SHORT_LABELS[s]) {
            return EXACT_SHORT_LABELS[s];
        }

        if (s.length > 4) {
            if (s.indexOf('與') !== -1) {
                var preAnd = s.split('與')[0].trim();
                if (preAnd && preAnd.length >= 3) s = preAnd;
            }
            if (EXACT_SHORT_LABELS[s]) {
                return EXACT_SHORT_LABELS[s];
            }
            var ringMatch = s.match(/^(?:三水|講堂|分家|西門|百工)?(內環|外環)(.+)$/);
            if (ringMatch) {
                var ringType = ringMatch[1];
                var sub = ringMatch[2];
                if (sub.length === 3 && (sub.endsWith('段') || sub.endsWith('口') || sub.endsWith('隅'))) {
                    s = ringType + sub.slice(0, 2);
                } else if (sub.length === 2) {
                    s = ringType + sub;
                } else if (sub.length > 2) {
                    s = ringType + sub.slice(0, 2);
                } else {
                    s = ringType + sub;
                }
            }
            if (EXACT_SHORT_LABELS[s]) {
                return EXACT_SHORT_LABELS[s];
            }
            if (s.length <= 4) {
                return s;
            }
            var prefixMatch = s.match(/^(講堂街|分家巷|三水口|西門|東橋|南門|北門|東門)/);
            if (prefixMatch) {
                var pfx = prefixMatch[1];
                var remainder = s.slice(pfx.length);
                if (remainder.length >= 3) {
                    s = remainder;
                } else if (remainder.length === 2) {
                    var condensedPfx = pfx.length === 3 ? pfx.slice(0, 2) : pfx;
                    s = condensedPfx + remainder;
                }
            }
            if (EXACT_SHORT_LABELS[s]) {
                return EXACT_SHORT_LABELS[s];
            }
            // 當路名帶有 北口、南口、東口、西口、北段、南段、東段、西段、中段、內口、外口 等時，保留方位特徵字於 4 字簡稱中
            var segMatch = s.match(/(北[一二三四五六七八九]?段|南[一二三四五六七八九]?段|東[一二三四五六七八九]?段|西[一二三四五六七八九]?段|中段|北西口|北東口|南西口|南東口|北口|南口|東口|西口|內口|外口)$/);
            if (segMatch) {
                var segTag = segMatch[1];
                var segBase = s.slice(0, -segTag.length);
                if (segTag === '中段' && segBase.length === 3) {
                    s = segBase + '中';
                } else {
                    var coreBase = segBase.replace(/(石階道|青石道|石板道|石板街|車馬街|林蔭道|夾道|廊道|石道|街道|街|巷|道)$/, '');
                    var shortTag = (segTag.length === 3 && (segTag.endsWith('段') || segTag.endsWith('口'))) ? segTag.slice(0, 2) : segTag;
                    if (coreBase.length >= 2) {
                        s = coreBase.slice(0, 2) + shortTag;
                    } else if (segBase.length >= 2) {
                        s = segBase.slice(0, 2) + shortTag;
                    } else {
                        s = (segBase + shortTag).slice(0, 4);
                    }
                }
            }
            if (EXACT_SHORT_LABELS[s]) {
                return EXACT_SHORT_LABELS[s];
            }
            if (s.length > 4) {
                // 幹道/長橋/大道/山道/棧道等 5 字以上路名優先提煉清晰 4 字語意名
                var trunkMatch = s.match(/^(.+?)(大道|幹道|山道|棧道|長橋|險徑|隘道)$/);
                if (trunkMatch) {
                    var preRoad = trunkMatch[1];
                    var roadSuf = trunkMatch[2];
                    if (preRoad.indexOf('跨海') !== -1) {
                        s = '跨海長橋';
                    } else if (preRoad.length >= 2) {
                        s = preRoad.slice(0, 2) + roadSuf;
                    } else {
                        s = preRoad + roadSuf;
                    }
                } else {
                    var suffixMatch = s.match(/(街|巷|道|橋|門|閣|堂|坊|館|居|宅|院|舍|鋪|行|站|台|坪|苑|園|樓|口|場|埠|廠|棧|庫|窯|塢|寮|莊|築|段|哨|所)$/);
                    if (suffixMatch) {
                        var suf = suffixMatch[1];
                        var candidate = s.slice(0, 3) + suf;
                        if (/[與之的]$/.test(candidate.slice(0, 3))) {
                            candidate = s.slice(0, 2) + s.slice(-2);
                        }
                        s = candidate;
                    } else if (/(?:[一二三四五六七八九十]號)$/.test(s)) {
                        s = s.slice(0, 2) + s.slice(-2);
                    } else {
                        s = s.slice(0, 4);
                    }
                }
            }
            if (s.length > 4 && /(?:[一二三四五六七八九十]號)$/.test(s)) {
                s = s.slice(0, 2) + s.slice(-2);
            }
            while (s.length > 2 && /[與之的]$/.test(s)) {
                s = s.slice(0, -1);
            }
            if (s.length > 4) {
                if (/(?:[一二三四五六七八九十]號)$/.test(s)) {
                    s = s.slice(0, 2) + s.slice(-2);
                } else {
                    s = s.slice(0, 4);
                }
            }
        }
        return s;
    }

