/// 依據場所名稱或聚落名稱查詢關聯的日常劇本切面（若無直接命中則依雜湊挑選 2 齣當日地方劇本）
pub fn scripts_for_room(room_name: &str) -> Vec<&'static PeninsulaScriptEntry> {
    let settlement = room_name.split('・').next().unwrap_or(room_name).trim();
    let mut matched: Vec<&'static PeninsulaScriptEntry> = PENINSULA_DAILY_SCRIPTS
        .iter()
        .filter(|s| {
            (!settlement.is_empty() && s.location_and_npc.contains(settlement))
                || s.location_and_npc.contains(room_name)
        })
        .collect();
    if matched.is_empty() {
        let hash = room_name.bytes().fold(17usize, |acc, b| acc.wrapping_mul(31).wrapping_add(b as usize));
        let total = PENINSULA_DAILY_SCRIPTS.len();
        matched.push(&PENINSULA_DAILY_SCRIPTS[hash % total]);
        matched.push(&PENINSULA_DAILY_SCRIPTS[(hash + 37) % total]);
    }
    matched
}

/// 依劇本編號查詢單一劇本切面
pub fn find_script_by_id(script_id: &str) -> Option<&'static PeninsulaScriptEntry> {
    PENINSULA_DAILY_SCRIPTS.iter().find(|s| s.id.eq_ignore_ascii_case(script_id))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn peninsula_daily_scripts_count_and_no_forbidden_tokens() {
        assert_eq!(PENINSULA_DAILY_SCRIPTS.len(), 108);
        let forbidden = ["debug", "資料庫", "database", "grid", "scene_stub", "還有"];
        for sc in PENINSULA_DAILY_SCRIPTS {
            for token in forbidden {
                assert!(
                    !sc.title.to_lowercase().contains(token)
                        && !sc.trigger_and_causal_chain.to_lowercase().contains(token)
                        && !sc.player_actions.to_lowercase().contains(token)
                        && !sc.outcome_and_world_change.to_lowercase().contains(token),
                    "script {} contains forbidden token {}",
                    sc.id,
                    token
                );
            }
        }
        let wen_yao_scripts = scripts_for_room("文曜・公議堂");
        assert!(!wen_yao_scripts.is_empty());
        assert!(find_script_by_id("WS-001").is_some());
        assert!(find_script_by_id("WS-108").is_some());
    }
}
