    #[test]
    fn test_no_meta_design_terms_in_player_facing_sources() {
        let forbidden_meta_terms = [
            "事件包",
            "劇本包",
            "劇本演繹",
            "場上劇本",
            "對口協力",
            "事件包與劇本包聯動",
            "第 1/3 幕",
            "第 2/3 幕",
            "第 3/3 幕",
            "第 {}/3 幕",
            "關鍵器物：",
            "這是白塔半島常見的",
            "【產地溯源：",
        ];

        let sources = [
            ("src/game/peninsula_scripts.rs", include_str!("../../game/peninsula_scripts.rs")),
            ("src/game/player_scene.rs", include_str!("../../game/player_scene.rs")),
            ("src/server/handler/movement.rs", include_str!("../../server/handler/movement.rs")),
            ("src/server/action/look.rs", include_str!("../../server/action/look.rs")),
            ("src/server/action/object.rs", include_str!("../../server/action/object.rs")),
            ("src/server/action/talk.rs", include_str!("../../server/action/talk.rs")),
            ("src/server/action/trade.rs", include_str!("../../server/action/trade.rs")),
            ("src/npc/brain_arrival.rs", include_str!("../../npc/brain_arrival.rs")),
            ("src/npc/grid_ai/decision.rs", include_str!("../../npc/grid_ai/decision.rs")),
            ("src/npcnpc/trigger.rs", include_str!("../../npcnpc/trigger.rs")),
            ("src/ai/talk.rs", include_str!("../../ai/talk.rs")),
        ];

        for (path, content) in sources {
            let mut in_test_module = false;
            for (line_no, raw_line) in content.lines().enumerate() {
                let trimmed = raw_line.trim();
                if trimmed.starts_with("#[cfg(test)]") || trimmed.starts_with("mod tests") {
                    in_test_module = true;
                }
                if in_test_module {
                    continue;
                }
                // Skip single-line comments and doc comments
                if trimmed.starts_with("//") || trimmed.starts_with("///") || trimmed.starts_with("//!") {
                    continue;
                }
                // Cut off inline comments if any
                let code_part = if let Some(idx) = raw_line.find("//") {
                    &raw_line[..idx]
                } else {
                    raw_line
                };
                for token in forbidden_meta_terms {
                    assert!(
                        !code_part.contains(token),
                        "Line {}:{} in {} contains forbidden meta-design term 「{}」: {}",
                        path,
                        line_no + 1,
                        path,
                        token,
                        trimmed
                    );
                }
            }
        }
    }

