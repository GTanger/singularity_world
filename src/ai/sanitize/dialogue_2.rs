/// 清理後台詞；若應丟棄則回傳空字串。
pub fn sanitize_npc_dialogue_line(line: &str) -> String {
    let s = sanitize_npc_dialogue_part1(line);
    if s.is_empty() {
        return String::new();
    }
    sanitize_npc_dialogue_part2(s)
}

/// 檢查台詞是否包含未登錄的幻影場所或非正典器物名稱。
pub fn contains_unregistered_phantom_venue(text: &str) -> bool {
    const FORBIDDEN_PHANTOM_VENUES: &[&str] = &[
        "燈籠鋪",
        "牛角燈",
        "聯運站前街",
        "西門東街",
        "北津石板拱橋",
        "西虹石板拱橋",
    ];
    FORBIDDEN_PHANTOM_VENUES.iter().any(|&phantom| text.contains(phantom))
}

/// 清理立即性時間詞副詞與動詞複合詞，防止出現「吃過完」、「檢視過查完」等重疊贅詞。
pub fn strip_immediate_temporal_words(text: &str) -> String {
    sanitize_npc_dialogue_part2(text.to_string())
}

/// 依據半島當前天色時辰調整台詞問候語，夜深時段替換晨間問候。
pub fn align_dialogue_sky_time(text: &str, hour: u32) -> String {
    if (0..5).contains(&hour) || hour >= 19 {
        text.replace("早啊！", "夜深了！")
            .replace("早啊，", "夜深了，")
            .replace("早安！", "夜安！")
            .replace("早安，", "夜裡風涼，")
    } else {
        text.to_string()
    }
}
