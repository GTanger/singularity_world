// NPC 台詞清理，對齊既有 ai/sanitize。

use crate::gametext;

include!("sanitize/zh_part1.rs");
include!("sanitize/zh_part2.rs");
include!("sanitize/zh_part3.rs");

pub fn normalize_simplified_to_traditional_zh(input: &str) -> String {
    let mut s: String = input
        .chars()
        .map(|c| {
            map_simplified_char_part1(c)
                .or_else(|| map_simplified_char_part2(c))
                .or_else(|| map_simplified_char_part3(c))
                .unwrap_or(c)
        })
        .collect();
    for (bad, good) in [
        ("店里", "店裡"),
        ("屋里", "屋裡"),
        ("山里", "山裡"),
        ("水里", "水裡"),
        ("手里", "手裡"),
        ("心里", "心裡"),
        ("夜里", "夜裡"),
        ("城里", "城裡"),
        ("村里", "村裡"),
        ("院里", "院裡"),
        ("哪里", "哪裡"),
        ("這里", "這裡"),
        ("那里", "那裡"),
        ("筑起", "築起"),
        ("修筑", "修築"),
        ("建筑", "建築"),
        ("示范", "示範"),
        ("防范", "防範"),
        ("范圍", "範圍"),
        ("憂郁", "憂鬱"),
        ("郁悶", "鬱悶"),
        ("咱們", "我們"),
        ("熱乎乎", "熱騰騰"),
        ("暖乎乎", "暖烘烘"),
        ("獅子", "石虎"),
        ("駱駝", "馱獸"),
        ("大象", "巨獸"),
        ("髮麻", "發麻"),
        ("髮抖", "發抖"),
        ("髮冷", "發冷"),
        ("髮熱", "發熱"),
        ("髮慌", "發慌"),
        ("髮愁", "發愁"),
        ("髮呆", "發呆"),
        ("髮現", "發現"),
        ("髮生", "發生"),
        ("出髮", "出發"),
        ("髮覺", "發覺"),
        ("髮揮", "發揮"),
        ("发麻", "發麻"),
        ("发抖", "發抖"),
        ("发冷", "發冷"),
        ("发熱", "發熱"),
        ("发慌", "發慌"),
        ("发愁", "發愁"),
        ("发呆", "發呆"),
        ("发現", "發現"),
        ("发生", "發生"),
        ("出发", "出發"),
        ("发覺", "發覺"),
        ("发揮", "發揮"),
        ("頭发", "頭髮"),
        ("白发", "白髮"),
        ("那伙人", "那夥人"),
        ("這伙人", "這夥人"),
        ("一伙人", "一夥人"),
        ("同伙", "同夥"),
        ("合伙", "合夥"),
        ("入伙", "入夥"),
        ("散伙", "散夥"),
        ("大伙兒", "大夥"),
        ("大伙", "大夥"),
        ("伙計", "夥計"),
        ("小伙子", "年輕人"),
        ("小伙", "年輕人"),
        ("好家伙", "好傢伙"),
        ("老家伙", "老傢伙"),
        ("家伙", "傢伙"),
    ] {
        if s.contains(bad) {
            s = s.replace(bad, good);
        }
    }
    s
}

