/// 移除行首「Name:」或「Name：」前綴。
pub fn strip_npc_line_speaker_prefix(line: &str, names: &[&str]) -> String {
    let mut line = normalize_simplified_to_traditional_zh(line.trim());
    for name in names {
        if name.is_empty() {
            continue;
        }
        let colon = format!("{name}:");
        if line.starts_with(&colon) {
            line = line[colon.len()..].trim().to_string();
            break;
        }
        let fullwidth = format!("{name}：");
        if line.starts_with(&fullwidth) {
            line = line[fullwidth.len()..].trim().to_string();
            break;
        }
    }
    if let Some(pos) = line.find(['：', ':']) {
        let prefix = &line[..pos];
        let prefix_chars: Vec<char> = prefix.chars().collect();
        const VERB_CLAUSE_CHARS: &[char] = &[
            '說', '道', '看', '想', '聽', '笑', '嘆', '問', '回', '在', '從', '往', '把', '被',
        ];
        if (2..=3).contains(&prefix_chars.len())
            && prefix_chars.iter().all(|c| ('\u{4E00}'..='\u{9FFF}').contains(c))
            && !prefix_chars.iter().any(|c| VERB_CLAUSE_CHARS.contains(c))
        {
            let col_len = if line[pos..].starts_with('：') {
                '：'.len_utf8()
            } else {
                ':'.len_utf8()
            };
            let rest = line[pos + col_len..].trim();
            if rest.chars().count() >= 4 {
                line = rest.to_string();
            }
        }
    }
    if let Some(&speaker) = names.first()
        && !speaker.is_empty()
    {
        for sep in ["，", "、", ","] {
            let self_vocative = format!("{speaker}{sep}");
            if line.starts_with(&self_vocative) {
                let rest = line[self_vocative.len()..].trim();
                if let Some(&listener) = names.get(1)
                    && !listener.is_empty()
                    && !rest.starts_with(listener)
                {
                    line = format!("{listener}，{rest}");
                } else {
                    line = rest.to_string();
                }
                break;
            }
        }
    }
    line
}

/// 移除對話中遺留的 WT-XXXX 編號（如 WT-0893 或剝除英文字母後的殘留 -0893）
pub fn strip_wt_catalog_codes(input: &str) -> String {
    let chars: Vec<char> = input.chars().collect();
    let mut out = String::with_capacity(input.len());
    let mut i = 0;
    let n = chars.len();
    while i < n {
        if i + 3 <= n && chars[i] == 'W' && chars[i + 1] == 'T' && chars[i + 2] == '-' {
            let mut j = i + 3;
            let mut digit_count = 0;
            while j < n && chars[j].is_ascii_digit() {
                digit_count += 1;
                j += 1;
            }
            if (3..=4).contains(&digit_count) {
                while j < n && (chars[j] == ' ' || chars[j] == '\t') {
                    j += 1;
                }
                i = j;
                continue;
            }
        }
        if chars[i] == '-' && i + 1 < n && chars[i + 1].is_ascii_digit() {
            let prev_is_digit = i > 0 && chars[i - 1].is_ascii_digit();
            if !prev_is_digit {
                let mut j = i + 1;
                let mut digit_count = 0;
                while j < n && chars[j].is_ascii_digit() {
                    digit_count += 1;
                    j += 1;
                }
                if (3..=4).contains(&digit_count) {
                    while j < n && (chars[j] == ' ' || chars[j] == '\t') {
                        j += 1;
                    }
                    i = j;
                    continue;
                }
            }
        }
        out.push(chars[i]);
        i += 1;
    }
    out
}

